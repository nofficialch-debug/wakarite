import type { PresetQuestion, QuestionBankType } from "@/lib/types";

type FourChoice = [string, string, string, string, string];

function makeQuestions(rows: FourChoice[]): PresetQuestion[] {
  return rows.map(([question_text, option_a, option_b, option_c, option_d]) => ({
    question_text,
    option_a,
    option_b,
    option_c,
    option_d
  }));
}

